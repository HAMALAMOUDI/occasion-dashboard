// Imports the Hikayati invitation card templates (designs/hikayati/*.dc.html,
// exported from the "Hikayati Invitation Cards" Claude design canvas) into
// lib/designs/markup.generated.ts.
//
// Each source file holds 20 layouts as <sc-if value="{{L<n>}}"> blocks inside
// one fixed-size root <div>. We keep each layout's markup verbatim — palettes,
// fonts and text are filled in at render time by lib/designs/engine.ts.
//
// Run after updating the .dc.html files:  node scripts/import-designs.mjs

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SOURCES = { classic: "designs/hikayati/classic.dc.html", modern: "designs/hikayati/modern.dc.html" };

const decode = (s) => s.replace(/&amp;/g, "&");

function parse(file) {
  const src = fs.readFileSync(path.join(ROOT, file), "utf8");
  const xdc = src.slice(src.indexOf("<x-dc>") + 6, src.indexOf("</x-dc>"));

  const fontsHref = /<link rel="stylesheet" href="([^"]+)"/.exec(xdc)?.[1];
  if (!fontsHref) throw new Error(`${file}: no font stylesheet`);

  const body = xdc.slice(xdc.indexOf("</helmet>") + 9).trim();
  const rootOpen = /^<div [^>]*>/.exec(body)?.[0];
  if (!rootOpen) throw new Error(`${file}: no root <div>`);
  const inner = body.slice(rootOpen.length, body.lastIndexOf("</div>"));

  // Walk top-level <sc-if value="{{Ln}}"> blocks, matching nested sc-if tags.
  const layouts = [];
  const tag = /<!--\s*(.*?)\s*-->|<(\/?)sc-if\b([^>]*)>/g;
  let depth = 0, start = -1, n = 0, title = "", lastComment = "", m;
  while ((m = tag.exec(inner))) {
    if (m[1] !== undefined) {
      if (depth === 0) lastComment = m[1];
      continue;
    }
    if (m[2] === "/") {
      depth--;
      if (depth === 0) layouts.push({ n, title, markup: inner.slice(start, m.index).trim() });
    } else {
      if (depth === 0) {
        const layout = /value="\{\{L(\d+)\}\}"/.exec(m[3]);
        if (!layout) throw new Error(`${file}: unexpected top-level sc-if`);
        n = Number(layout[1]);
        title = lastComment.replace(/^[A-Z]?\d+\s*·\s*/, "");
        start = m.index + m[0].length;
      }
      depth++;
    }
  }
  if (layouts.length !== 20 || layouts.some((l, i) => l.n !== i + 1)) throw new Error(`${file}: expected layouts 1–20`);
  return { fontsHref: decode(fontsHref), root: rootOpen, layouts };
}

const out = {};
for (const [style, file] of Object.entries(SOURCES)) out[style] = parse(file);

const header = `// GENERATED by scripts/import-designs.mjs from designs/hikayati/*.dc.html — do not edit by hand.\n\n`;
const body = `export const MARKUP = ${JSON.stringify(out, null, 1)} as const;\n`;
fs.writeFileSync(path.join(ROOT, "lib/designs/markup.generated.ts"), header + body);
for (const [style, v] of Object.entries(out)) console.log(`${style}: ${v.layouts.length} layouts — ${v.layouts.map((l) => l.title).join(", ")}`);
